package moneywords

import (
	"testing"

	"github.com/shopspring/decimal"
)

func TestRubles(t *testing.T) {
	cases := map[string]string{
		"0":          "Ноль рублей 00 копеек",
		"1":          "Один рубль 00 копеек",
		"2.01":       "Два рубля 01 копейка",
		"11.11":      "Одиннадцать рублей 11 копеек",
		"21.22":      "Двадцать один рубль 22 копейки",
		"1000":       "Одна тысяча рублей 00 копеек",
		"2000":       "Две тысячи рублей 00 копеек",
		"5000":       "Пять тысяч рублей 00 копеек",
		"1234.56":    "Одна тысяча двести тридцать четыре рубля 56 копеек",
		"12512.5":    "Двенадцать тысяч пятьсот двенадцать рублей 50 копеек",
		"1000000":    "Один миллион рублей 00 копеек",
		"2003004.99": "Два миллиона три тысячи четыре рубля 99 копеек",
		"111111":     "Сто одиннадцать тысяч сто одиннадцать рублей 00 копеек",
		"999.999":    "Одна тысяча рублей 00 копеек",
	}
	for in, want := range cases {
		if got := Rubles(decimal.RequireFromString(in)); got != want {
			t.Errorf("Rubles(%s) = %q, want %q", in, got, want)
		}
	}
}

func TestPlural(t *testing.T) {
	for n, want := range map[int64]string{1: "a", 2: "b", 4: "b", 5: "c", 11: "c", 14: "c", 21: "a", 22: "b", 111: "c", 101: "a"} {
		if got := Plural(n, "a", "b", "c"); got != want {
			t.Errorf("Plural(%d) = %q, want %q", n, got, want)
		}
	}
}
